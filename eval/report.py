"""Write eval/results.md from eval/results.json and the runs.

    uv run python -m eval.score && uv run python -m eval.report

Every number in the file comes from the scored runs, so the report cannot drift from them. The prose that
interprets the numbers is in docs/benchmark.md.
"""

from __future__ import annotations

import json
from collections.abc import Callable
from typing import Any

from eval.run import RUNS, golden
from eval.score import NAMES_ORDER, OUT
from gonogo.paths import ROOT

REPORT = ROOT / "eval" / "results.md"
LABEL = {
    "A": "A. Vector RAG",
    "B": "B. Graph agent",
    "C": "C. Rules only",
    "C+": "C+. Rules with a model reader",
}


def cell(v: Any, suffix: str = "") -> str:
    return "n/a" if v is None else f"{v}{suffix}"


def runs() -> dict[str, dict[str, dict[str, Any]]]:
    return {
        p.stem: {a["qid"]: a for a in map(json.loads, p.read_text().splitlines()) if a}
        for p in sorted(RUNS.glob("*.jsonl"))
    }


def render() -> str:
    res = json.loads(OUT.read_text())
    names = [n for n in NAMES_ORDER if n in res]
    qs = {q["qid"]: q for q in golden()}
    answers = runs()
    out = [
        "# Benchmark results",
        "",
        f"Generated by `eval/report.py` from `eval/results.json`. {len(qs)} questions, "
        f"{len({q['case_id'] for q in qs.values()})} cases. Method: [docs/benchmark.md](../docs/benchmark.md).",
        "",
        "## Summary",
        "",
        "| | " + " | ".join(LABEL[n] for n in names) + " |",
        "|---|" + "---:|" * len(names),
    ]
    rows: list[tuple[str, Callable[[dict[str, Any]], str]]] = [
        ("Verdict accuracy", lambda r: cell(r["accuracy"], "%")),
        ("Cases with all four wordings right", lambda r: cell(r["case_accuracy"], "%")),
        ("**False GO** (answered GO, should not be)", lambda r: f"**{len(r['false_go'])}**"),
        ("False GO rate", lambda r: cell(r["false_go_rate"], "%")),
        ("Missed GO rate", lambda r: cell(r["missed_go_rate"], "%")),
        ("Citation precision", lambda r: cell(r["citation_precision"], "%")),
        ("Cites the decisive agreement", lambda r: cell(r["decisive_recall"], "%")),
        ("Search returned a record of the patent", lambda r: cell(r.get("retrieval_hit_rate"), "%")),
        ("Median latency", lambda r: cell(r["latency_p50_s"], " s")),
        ("95th percentile latency", lambda r: cell(r["latency_p95_s"], " s")),
        ("Model calls", lambda r: f"{r['model_calls']:,}"),
        ("Tokens in / out", lambda r: f"{r['tokens_in']:,} / {r['tokens_out']:,}"),
        ("Model cost (Haiku 4.5 on-demand)", lambda r: f"${r['model_cost_usd']:.2f}"),
        ("Errors", lambda r: str(r["errors"])),
    ]
    for label, fn in rows:
        out.append(f"| {label} | " + " | ".join(fn(res[n]) for n in names) + " |")

    head = "| Family | Questions | " + " | ".join(LABEL[n] for n in names) + " |"
    out += ["", "## Accuracy by question family", "", head, "|---|---:|" + "---:|" * len(names)]
    families = sorted(next(iter(res.values()))["accuracy_by_family"])
    for f in families:
        total = res[names[0]]["accuracy_by_family"][f][1]
        cells = []
        for n in names:
            ok, count = res[n]["accuracy_by_family"].get(f, [0, 0])
            cells.append(f"{ok}/{count}")
        out.append(f"| {f} | {total} | " + " | ".join(cells) + " |")

    head = "| Wording | " + " | ".join(LABEL[n] for n in names) + " |"
    out += ["", "## Accuracy by wording", "", head, "|---|" + "---:|" * len(names)]
    for style in ("formal", "casual", "terse", "noisy", "unanswerable"):
        out.append(
            f"| {style} | " + " | ".join(cell(res[n]["accuracy_by_style"].get(style), "%") for n in names) + " |"
        )

    out += ["", "## Every false GO", ""]
    any_false = False
    for n in names:
        for qid in res[n]["false_go"]:
            any_false = True
            q, a = qs[qid], answers[n][qid]
            out += [
                f"**{LABEL[n]}, {qid}** ({q['case_type']}). The right answer is {q['expected_verdict']}.",
                "",
                f"> {q['text']}",
                "",
                f"Reason given: {a['reason'] or 'none'}",
                "",
            ]
    if not any_false:
        out.append("None.")

    out += ["", "## Verdicts given, by right answer", ""]
    for n in names:
        out += [f"**{LABEL[n]}**", "", "| Right answer | Said | Questions |", "|---|---|---:|"]
        for key, count in res[n]["confusion"].items():
            right, said = key.split(" -> ")
            if right != said:
                out.append(f"| {right} | {said} | {count} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


if __name__ == "__main__":
    REPORT.write_text(render())
    print("wrote", REPORT.relative_to(ROOT))
